#!/usr/bin/env node
/**
 * Generates src/app/loomit-tokens.css from design/loomit-tokens.json, the
 * token export of the org's "loomit" Design System ("Calm Glass").
 * Values are never retyped by hand: update the JSON and re-run
 * `npm run tokens`.
 *
 * Only product-relevant groups are emitted (colors, radius, shadows,
 * gradients, font families). Deck-only slide geometry (canvas, slide
 * coordinates) is intentionally skipped.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "design/loomit-tokens.json");
const target = resolve(root, "src/app/loomit-tokens.css");
const tokens = JSON.parse(readFileSync(source, "utf8"));

const colors = new Map(tokens.color.tokens.map((token) => [token.name, token.value]));

function resolveColor(value, theme) {
  const raw = typeof value === "string" ? value : value[theme];
  const reference = /^\{(.+)\}$/.exec(raw);
  return reference ? resolveColor(colors.get(reference[1]), theme) : raw;
}

function block(theme) {
  const lines = [];
  lines.push("  /* Color */");
  for (const token of tokens.color.tokens) {
    lines.push(`  --${token.name}: ${resolveColor(token.value, theme)};`);
  }
  lines.push("", "  /* Type */");
  for (const [name, value] of Object.entries(tokens.type.families)) {
    lines.push(`  --font-${name}: ${value};`);
  }
  for (const group of ["radius", "shadow", "gradient"]) {
    lines.push("", `  /* ${group[0].toUpperCase()}${group.slice(1)} */`);
    for (const token of tokens[group].tokens) {
      lines.push(`  --${token.name}: ${token.value};`);
    }
  }
  return lines.join("\n");
}

const css = `/*
 * GENERATED by scripts/generate-loomit-tokens.mjs from design/loomit-tokens.json
 * (${tokens.meta?.source ?? tokens.name}). Do not edit by hand.
 */

:root {
${block("light")}
}

[data-theme="dark"] {
${tokens.color.tokens
  .filter((token) => typeof token.value === "object")
  .map((token) => `  --${token.name}: ${resolveColor(token.value, "dark")};`)
  .join("\n")}
}
`;

writeFileSync(target, css);
console.log(`Wrote ${target}`);
